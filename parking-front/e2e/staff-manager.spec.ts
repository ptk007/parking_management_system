import { test, expect } from '@playwright/test'
test.use({headless:true})
test('staff management presents the empty state, form and staff cards consistently', async ({page},info) => {
  await page.addInitScript(() => {
    localStorage.setItem('token','staff-style-test')
    localStorage.setItem('user',JSON.stringify({_id:'admin1',name:'Admin',role:'admin',status:'online'}))
  })
  await page.route('**/api/**',route=>route.fulfill({json:{floors:[],buildings:[],tickets:[]}}))
  await page.setViewportSize({width:1366,height:768})
  await page.goto('/admin/staff')
  await expect(page.getByRole('heading',{name:'Staff Manager',exact:true})).toBeVisible()
  await expect(page.locator('.staff-count')).toHaveText('0')
  await expect(page.getByRole('heading',{name:'No staff yet',exact:true})).toBeVisible()
  const icon=(await page.locator('.staff-empty-icon').boundingBox())!
  const empty=(await page.locator('.staff-empty').boundingBox())!
  expect(Math.abs(icon.x+icon.width/2-empty.x-empty.width/2)).toBeLessThan(2)
  await page.screenshot({path:info.outputPath('staff-empty.png'),fullPage:true})
  await page.getByRole('button',{name:'Add your first staff',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Add Staff',exact:true})).toBeVisible()
  await page.getByLabel('Staff Name :',{exact:true}).fill('Test Staff')
  await page.getByLabel('Username :',{exact:true}).fill('teststaff')
  await page.getByLabel('Password :',{exact:true}).fill('testpassword')
  await page.getByLabel('Confirm Password :',{exact:true}).fill('testpassword')
  await page.screenshot({path:info.outputPath('staff-form.png'),fullPage:true})
  await page.setViewportSize({width:750,height:1000})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('staff-form-narrow.png'),fullPage:true})
  await page.getByRole('button',{name:'Add',exact:true}).click()
  await expect(page.locator('.staff-count')).toHaveText('1')
  await expect(page.locator('.staff-card')).toContainText('Test Staff')
  await page.getByRole('button',{name:'Edit staff',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Edit Staff',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Back to Staff List',exact:true}).click()
  await expect(page.locator('.staff-card')).toHaveCount(1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('staff-list-narrow.png'),fullPage:true})
  await page.setViewportSize({width:1366,height:768})
  await page.screenshot({path:info.outputPath('staff-list.png'),fullPage:true})
})
